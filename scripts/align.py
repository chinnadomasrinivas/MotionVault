 ("PROBLEM","Telugu matladi Japan vaallaki cheppinattu."),
 ("PROBLEM","Mari code ela run avuthundi?"),
 ("STEP1","Step 1:"),("STEP1","Run nokkagane,"),
 ("STEP1","IDE background lo python file.py command run chesthundi."),
 ("STEP2","Step 2:"),("STEP2","Interpreter mee code ni check chesi,"),("STEP2","bytecode ga marusthundi."),
 ("STEP2","Idi oka translator laantidi!"),
 ("STEP3","Step 3:"),
 ("STEP3","Python Virtual Machine aa bytecode ni okkokka instruction ga chaduvthundi."),
 ("STEP3","Oka chef recipe steps follow ayyinattu!"),
 ("QUIZ","Quick question:"),("QUIZ","Python compiled language aa,"),("QUIZ","interpreted language aa?"),
 ("QUIZ","Answer cheppandi,"),("QUIZ","comments lo!"),
 ("ANSWER","Answer:"),("ANSWER","Rendu!"),("ANSWER","First compile avuthundi,"),("ANSWER","tarvata interpret avuthundi."),
 ("HW","Step 4, 5:"),("HW","VM kuda oka C program."),("HW","OS dani CPU ki isthundi,"),
 ("HW","CPU machine instructions run chesthundi."),("HW","Output screen meeda!"),
